/**
 * Чистый парсер SSE-кадров (`src/api/sse.ts` в 02-design.md): без ввода-вывода, без fetch и DOM —
 * поэтому тестируется офлайн обычными строками (NFR-01, T-12).
 *
 * Формат кадра, который шлёт бэк (ChatRouting.kt): `event: chunk\ndata: {"text":"…"}\n\n`.
 * Правила разбора, которые обязан реализовать `createSseParser`:
 *   - кадры разделяются пустой строкой; переводы строк — и `\n`, и `\r\n` (кадр может прийти
 *     разрезанным между `\r` и `\n` — разделитель обязан пережить границу двух `push`);
 *   - `data:` — payload; несколько подряд идущих `data:`-строк склеиваются через `\n`;
 *   - ровно один ведущий пробел после `data:`/`event:` отбрасывается (`data: {…}` → `{…}`);
 *   - строки-комментарии (`:`), `id:` и `retry:` игнорируются;
 *   - незавершённый кадр остаётся во внутреннем буфере и отдаётся только при появлении
 *     терминирующей пустой строки (последний неполный кадр не эмитится никогда);
 *   - кадр без строки `event:` получает имя по умолчанию `'message'` (SSE-спецификация);
 *     порядок событий = порядок кадров в потоке.
 *
 * Парсер не бросает исключений на мусоре: неизвестные поля и строки без `:` просто пропускаются.
 * Потребитель — `api/chatApi.ts`: он кормит парсер декодированными кусками тела ответа.
 */

/** Один завершённый SSE-кадр: имя события (`chunk`/`done`/`error`) и склеенный payload. */
export interface SseEvent {
  /** Значение строки `event:`; `'message'`, если строка отсутствовала. */
  event: string
  /** Значение всех строк `data:` кадра, склеенных через `\n` (сырой текст, без JSON-разбора). */
  data: string
}

/** Состояние парсера: буфер незавершённого кадра между вызовами `push` (создаётся на один ответ). */
export interface SseParser {
  /**
   * Скармливает очередной кусок текста и возвращает все кадры, которые завершились этим куском.
   * Побочные эффекты: мутирует только внутренний буфер парсера; при отсутствии полных кадров
   * возвращает пустой массив. Вызывается по одному куску на каждое чтение из ReadableStream,
   * без батчинга (NFR-05b).
   */
  push(text: string): SseEvent[]
}

/**
 * Создаёт независимый парсер с собственным буфером (на каждый запрос — свой экземпляр).
 * Возвращаемый объект сохраняет состояние между вызовами `push`, поэтому его нельзя переиспользовать
 * для двух потоков одновременно.
 */
export function createSseParser(): SseParser {
  /** Незавершённый кадр (и, возможно, висячий `\r`) между вызовами `push`. */
  let buffer = ''

  return {
    push(text: string): SseEvent[] {
      buffer += text

      // Висячий `\r` в конце буфера придерживаем: он может оказаться первой половиной
      // `\r\n`, разрезанного между двумя push.
      let heldCr = ''
      if (buffer.endsWith('\r')) {
        heldCr = '\r'
        buffer = buffer.slice(0, -1)
      }

      // Приводим переводы строк к `\n`; завершённые кадры отделены пустой строкой.
      const parts = buffer.replace(/\r\n/g, '\n').replace(/\r/g, '\n').split('\n\n')
      // Последний кусок — незавершённый кадр: он ждёт следующего push (терминатора ещё нет).
      buffer = (parts.pop() ?? '') + heldCr

      const events: SseEvent[] = []
      for (const part of parts) {
        const event = parseFrame(part)
        if (event !== null) events.push(event)
      }
      return events
    },
  }
}

/**
 * Разбирает один завершённый кадр (без терминирующей пустой строки).
 * Не бросает исключений на мусоре: строки без `:` и неизвестные поля пропускаются.
 *
 * @returns событие или `null`, если в кадре нет ни `event:`, ни `data:` (комментарий/пустой блок)
 */
function parseFrame(frame: string): SseEvent | null {
  let event = ''
  const dataLines: string[] = []

  for (const line of frame.split('\n')) {
    if (line === '' || line.startsWith(':')) continue // пустая строка и комментарий
    const colon = line.indexOf(':')
    if (colon === -1) continue // строка без `:` — поле с пустым значением, здесь не нужно
    const field = line.slice(0, colon)
    let value = line.slice(colon + 1)
    if (value.startsWith(' ')) value = value.slice(1) // ровно один ведущий пробел
    if (field === 'event') event = value
    else if (field === 'data') dataLines.push(value)
    // `id:`, `retry:` и любые неизвестные поля игнорируются (SSE-спецификация)
  }

  if (event === '' && dataLines.length === 0) return null
  return { event: event === '' ? 'message' : event, data: dataLines.join('\n') }
}
